import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = process.cwd();

function readJson(path) {
  return JSON.parse(readFileSync(resolve(root, path), 'utf8'));
}

function esc(value) {
  return String(value ?? '').replaceAll('|', '\\|').replaceAll('\n', '<br>');
}

function mdRef(ref) {
  if (!ref) return '—';
  if (ref.kind === 'path') return `\`${ref.value}\``;
  if (ref.kind === 'issue') return `issue \`${ref.value}\``;
  if (ref.kind === 'pr') return `PR \`${ref.value}\``;
  if (ref.kind === 'commit') return `commit \`${ref.value}\``;
  return `external \`${ref.value}\``;
}

function refs(list = []) {
  return list.length ? list.map(mdRef).join(', ') : '—';
}

function date(value) {
  return value ?? '—';
}

function renderState(company, freshness) {
  const counts = Object.fromEntries(
    freshness.semantics.allowed_statuses.map((status) => [
      status,
      freshness.objects.filter((entry) => entry.freshness_status === status).length,
    ]),
  );

  const workstreams = company.workstreams
    .map(
      (item) =>
        `| ${esc(item.label)} | \`${esc(item.status)}\` | ${esc(item.next_gate)} |`,
    )
    .join('\n');

  const gates = company.critical_gates
    .map(
      (gate) =>
        `| \`${esc(gate.id)}\` | ${esc(gate.domain)} | \`${esc(gate.status)}\` | ${esc(gate.question)} | ${esc(refs(gate.refs))} |`,
    )
    .join('\n');

  const phaseRefs = refs(company.company_phase.authority_refs);

  return `# EMOPET — Current Company State

**Snapshot date:** ${company.snapshot.date}  
**Snapshot base:** \`${company.snapshot.base_ref}@${company.snapshot.base_sha}\`  
**Status:** \`COMPANY STATE PROJECTION / NOT DOMAIN AUTHORITY\`  
**Machine-readable source:** \`state/company-state.json\`  
**Generated by:** \`scripts/control/generate-company-os-views.mjs\`

This page is generated from machine-readable Company OS state. Follow the cited controlling authority before making a substantive product, scientific, legal, industrial or funding decision.

## Phase

**${company.company_phase.statement}**

Authority: ${phaseRefs}.

Next gate: ${company.company_phase.next_gate}

## Workstream snapshot

| Workstream | Current projection | Next proof/gate |
|---|---|---|
${workstreams}

## Freshness / STALE overlay

Freshness is generated from \`state/freshness/freshness-state.json\` and remains separate from substantive status.

| Freshness state | Covered objects |
|---|---:|
${freshness.semantics.allowed_statuses.map((status) => `| \`${status}\` | ${counts[status]} |`).join('\n')}

${freshness.semantics.decision_rule}

Repository recency does not reset domain freshness.

## Critical company gates

| Gate | Domain | Status | Question | Refs |
|---|---|---|---|---|
${gates}

## Resource-allocation principle

The company should optimize for **high-impact uncertainty retired per unit of time and capital**, not for feature count.

Until the core proof gates move, platform-scale surfaces remain subordinate to physics, product value, economics, rights and launch readiness.

## Confidentiality

${company.confidentiality.rule}

See \`docs/records/README.md\` and \`docs/company/EMOPET_COMPANY_OS_ARCHITECTURE_2026-10-01.md\`.
`;
}

function renderCorporate(corporate) {
  const items = [
    corporate.entity,
    corporate.governance,
    ...corporate.rights_gates,
  ];

  const rows = items
    .map(
      (item) =>
        `| ${esc(item.label)} | \`${esc(item.status)}\` | ${esc(refs(item.authority_refs))} | ${esc(item.next_gate)} |`,
    )
    .join('\n');

  const forbidden = corporate.confidentiality.forbidden_public_fields
    .map((field) => `- \`${field}\``)
    .join('\n');

  return `# EMOPET — Corporate / IP State

> **Status:** \`PUBLIC-SAFE COMPANY OS PROJECTION / NOT LEGAL SIGN-OFF / NOT DOMAIN AUTHORITY\`  
> **Snapshot:** \`${corporate.snapshot.base_ref}@${corporate.snapshot.base_sha}\` on ${corporate.snapshot.date}  
> **Machine-readable source:** \`state/corporate/corporate-state.json\`  
> **Generated by:** \`scripts/control/generate-company-os-views.mjs\`

This view is generated from the public-safe Corporate/IP state. It does not decide ownership, licensing, entity structure, equity, legal compliance or release authority.

## Current public-safe projection

| Area | Projection | Controlling refs | Next gate |
|---|---|---|---|
${rows}

## Authority boundary

Repository history, file presence, supplier discussion, a licence label, a public data source or a contributor-role declaration does not by itself establish ownership, assignment, permitted product use or release authority.

The cited controlled source wins if this projection drifts.

## Confidentiality boundary

Repository visibility: \`${corporate.confidentiality.repository_visibility}\`

${corporate.confidentiality.safe_projection_rule}

Forbidden public fields:

${forbidden}

## Decision discipline

A gate may move from \`OPEN\` or \`HOLD\` only when the controlling authority records the underlying evidence and reviewed disposition.

This projection must never convert:

- a declaration into verified chain of title;
- source confirmation into product-use authorization;
- repository visibility into an open-source licence;
- a missing contributor record into proof of non-contribution;
- an implementation into legal clearance.
`;
}

function renderFreshness(freshness) {
  const semantics = [
    ['UNREVIEWED', freshness.semantics.unreviewed_rule],
    ['CURRENT', freshness.semantics.current_rule],
    ['REVIEW_DUE', freshness.semantics.review_due_rule],
    ['STALE', freshness.semantics.stale_rule],
    ['NOT_APPLICABLE', 'Freshness does not meaningfully apply; no promotion is implied.'],
  ];

  const counts = Object.fromEntries(
    freshness.semantics.allowed_statuses.map((status) => [
      status,
      freshness.objects.filter((entry) => entry.freshness_status === status).length,
    ]),
  );

  const objectRows = freshness.objects
    .map(
      (entry) =>
        `| \`${esc(entry.target_id)}\` | \`${esc(entry.freshness_status)}\` | ${date(entry.last_domain_review_at)} | ${date(entry.review_due_at)} | ${date(entry.stale_after)} | \`${esc(entry.decision_use)}\` |`,
    )
    .join('\n');

  const evidenceRows = freshness.evidence.length
    ? freshness.evidence
        .map(
          (entry) =>
            `| \`${esc(entry.id)}\` | ${esc(mdRef(entry.target_ref))} | \`${esc(entry.freshness_status)}\` | ${date(entry.review_due_at)} | ${date(entry.stale_after)} | \`${esc(entry.decision_use)}\` |`,
        )
        .join('\n')
    : '| — | — | — | — | — | — |';

  return `# EMOPET — Freshness / STALE State

> **Status:** \`COMPANY OS FRESHNESS PROJECTION / NOT DOMAIN AUTHORITY\`  
> **Snapshot:** \`${freshness.snapshot.base_ref}@${freshness.snapshot.base_sha}\` on ${freshness.snapshot.date}  
> **Machine-readable source:** \`state/freshness/freshness-state.json\`  
> **Generated by:** \`scripts/control/generate-company-os-views.mjs\`

Freshness is orthogonal to substantive status. A recent Git commit, file edit or evidence-file date does **not** automatically make the underlying claim fresh.

## Semantics

| Freshness state | Rule |
|---|---|
${semantics.map(([status, rule]) => `| \`${status}\` | ${esc(rule)} |`).join('\n')}

Decision rule: ${freshness.semantics.decision_rule}

## Coverage

State scope: \`${freshness.coverage.state_scope}\`  
Evidence scope: \`${freshness.coverage.evidence_scope}\`

| Freshness state | Covered objects |
|---|---:|
${freshness.semantics.allowed_statuses.map((status) => `| \`${status}\` | ${counts[status]} |`).join('\n')}

## Object review state

| Target | Freshness | Last domain review | Review due | Stale after | Decision use |
|---|---|---|---|---|---|
${objectRows}

## Evidence review state

| Evidence | Target | Freshness | Review due | Stale after | Decision use |
|---|---|---|---|---|---|
${evidenceRows}

## Rules

- Re-indexing an unchanged source does not reset freshness.
- Missing cadence remains missing; the Company OS must not invent a review interval to make a dashboard look complete.
- \`UNREVIEWED\`, \`REVIEW_DUE\`, and \`STALE\` fail closed for freshness-dependent strong claims.
- The controlling domain authority decides whether underlying evidence is valid. This layer only records review timing and decision-use constraints.
`;
}

export function renderCompanyOsViews() {
  const company = readJson('state/company-state.json');
  const corporate = readJson('state/corporate/corporate-state.json');
  const freshness = readJson('state/freshness/freshness-state.json');

  return {
    'STATE.md': renderState(company, freshness),
    'CORPORATE.md': renderCorporate(corporate),
    'FRESHNESS.md': renderFreshness(freshness),
  };
}

function checkViews(views) {
  const mismatches = [];
  for (const [path, expected] of Object.entries(views)) {
    const actual = readFileSync(resolve(root, path), 'utf8');
    if (actual !== expected) mismatches.push(path);
  }

  if (mismatches.length) {
    throw new Error(
      `Generated Company OS views are stale: ${mismatches.join(', ')}. Run node scripts/control/generate-company-os-views.mjs --write`,
    );
  }
}

function writeViews(views) {
  for (const [path, content] of Object.entries(views)) {
    writeFileSync(resolve(root, path), content, 'utf8');
  }
}

if (import.meta.url === `file://${process.argv[1].replaceAll('\\\\', '/')}`) {
  const views = renderCompanyOsViews();
  if (process.argv.includes('--write')) {
    writeViews(views);
  } else {
    checkViews(views);
  }
}
