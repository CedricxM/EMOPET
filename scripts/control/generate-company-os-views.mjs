export function renderCompanyOsViews() {
  const company = readJson('state/company-state.json');
  const corporate = readJson('state/corporate/corporate-state.json');
  const freshness = readJson('state/freshness/freshness-state.json');
  const milestone = readJson('state/milestones/MS-S1-PHYSICS.json');
  const matExperiment = readJson('state/experiments/EXP-MAT-INCREMENTAL-001.json');
  const tagExperiment = readJson('state/experiments/EXP-TAG-PHYSICAL-001.json');
  const finance = readJson('state/finance/finance-state.json');
  const preseed = readJson('state/finance/fundraising/PRESEED-CONDITIONAL-2027.json');
  const metricsState = readJson('state/metrics/metrics.json');
  const riskState = readJson('state/risks/risk-register.json');
  const unknownState = readJson('state/unknowns/critical-unknowns.json');

  return {
    'STATE.md': renderState(company, freshness),
    'CORPORATE.md': renderCorporate(corporate),
    'FRESHNESS.md': renderFreshness(freshness),
    'FOUNDER_COCKPIT.md': renderFounderCockpit(
      company,
      corporate,
      freshness,
      milestone,
      matExperiment,
      tagExperiment,
      finance,
      preseed,
      metricsState,
      riskState,
      unknownState,
    ),
    'INVESTOR_VIEW.md': renderInvestorView(
      company,
      corporate,
      freshness,
      milestone,
      finance,
      preseed,
      metricsState,
    ),
    'SUPPLIER_VIEW.md': renderSupplierView(
      company,
      corporate,
      freshness,
      milestone,
      matExperiment,
      tagExperiment,
      finance,
    ),
  };
}

function checkViews(views) {
  const mismatches = [];
  for (const [path, expected] of Object.entries(views)) {
    const actual = readFileSync(resolve(root, path), 'utf8');
    if (actual !== expected) mismatches.push(path);
  }

  if (mismatches.length) {
    throw new Error(
      `Generated Company OS views are stale: ${mismatches.join(', ')}. Run node scripts/control/generate-company-os-views.mjs --write`,
    );
  }
}

function writeViews(views) {
  for (const [path, content] of Object.entries(views)) {
    writeFileSync(resolve(root, path), content, 'utf8');
  }
}

const invokedPath = process.argv[1] ? resolve(process.argv[1]) : null;
if (invokedPath && fileURLToPath(import.meta.url) === invokedPath) {
  const views = renderCompanyOsViews();
  if (process.argv.includes('--write')) {
    writeViews(views);
  } else {
    checkViews(views);
  }
}
