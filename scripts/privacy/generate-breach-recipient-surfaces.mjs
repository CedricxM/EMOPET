import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
export const GENERATED_PATH = path.join(
  REPO_ROOT,
  'backend/api/privacy/breach-recipient-surfaces.generated.ts',
);

const ACCOUNT_TOPOLOGY = 'config/privacy/account-erasure-topology.json';
const DOG_TOPOLOGY = 'config/privacy/dog-erasure-topology.json';
const NON_SQL_INVENTORY = 'config/privacy/non-sql-erasure-surface-inventory.json';
const PROVIDER_EVIDENCE = 'config/privacy/provider-retention-erasure-evidence.json';
const WEB_ROOT = 'apps/web';

const PERSON_BEARING_STORE_RE = /\bbreiz-[a-z0-9-]+(?:requests|entries|posts|events|spots)\b/g;

function readJson(relativePath) {
  return JSON.parse(fs.readFileSync(path.join(REPO_ROOT, relativePath), 'utf8'));
}

function walkSourceFiles(root) {
  const out = [];
  for (const entry of fs.readdirSync(root, { withFileTypes: true })) {
    const absolute = path.join(root, entry.name);
    if (entry.isDirectory()) {
      out.push(...walkSourceFiles(absolute));
      continue;
    }
    if (/\.(?:ts|tsx|js|mjs)$/.test(entry.name)) out.push(absolute);
  }
  return out;
}

function uniqueSorted(values) {
  return [...new Set(values)].sort((left, right) => left.localeCompare(right));
}

export function deriveBreachRecipientSurfaces() {
  const account = readJson(ACCOUNT_TOPOLOGY);
  const dog = readJson(DOG_TOPOLOGY);
  const nonSql = readJson(NON_SQL_INVENTORY);
  const providerEvidence = readJson(PROVIDER_EVIDENCE);

  const canonicalSqlTables = uniqueSorted([
    account.subject.table,
    ...account.directUserReferences.map((entry) => entry.table),
    dog.subject.table,
    ...dog.canonicalForeignKeys.map((entry) => entry.table),
    ...dog.transitiveDescendants.map((entry) => entry.table),
  ]);

  const unconstrainedSqlTables = uniqueSorted([
    ...(dog.unconstrainedDogIdentifiers ?? []).map((entry) => entry.table),
    ...(dog.unconstrainedGrantIdentifiers ?? []).map((entry) => entry.table),
  ]).filter((table) => !canonicalSqlTables.includes(table));

  const nonSqlSurfaces = uniqueSorted(nonSql.surfaces.map((entry) => entry.surface));
  const providers = uniqueSorted(providerEvidence.providers.map((entry) => entry.provider));

  const webStores = new Set();
  for (const sourcePath of walkSourceFiles(path.join(REPO_ROOT, WEB_ROOT))) {
    const source = fs.readFileSync(sourcePath, 'utf8');
    for (const match of source.matchAll(PERSON_BEARING_STORE_RE)) webStores.add(match[0]);
  }

  return [
    ...canonicalSqlTables.map((name) => ({
      surface: 'sql:' + name,
      authority: 'CANONICAL_SQL',
      requiredGap: null,
      source: 'config/privacy account+dog erasure topology',
    })),
    ...unconstrainedSqlTables.map((name) => ({
      surface: 'sql:' + name,
      authority: 'SQL_UNCONSTRAINED_GAP_REQUIRED',
      requiredGap: 'canonical_subject_missing',
      source: 'config/privacy/dog-erasure-topology.json unconstrained identifiers',
    })),
    ...nonSqlSurfaces.map((name) => ({
      surface: 'non_sql:' + name,
      authority: 'NON_SQL_GAP_REQUIRED',
      requiredGap: 'canonical_subject_missing',
      source: NON_SQL_INVENTORY,
    })),
    ...providers.map((name) => ({
      surface: 'provider:' + name,
      authority: 'PROVIDER_GAP_REQUIRED',
      requiredGap: 'provider_copy_unverified',
      source: PROVIDER_EVIDENCE,
    })),
    ...uniqueSorted(webStores).map((name) => ({
      surface: 'web:' + name,
      authority: 'WEB_PROTOTYPE_GAP_REQUIRED',
      requiredGap: 'canonical_subject_missing',
      source: 'apps/web localStorage discovery',
    })),
  ].sort((left, right) => left.surface.localeCompare(right.surface));
}

export function renderGeneratedSource(catalogue) {
  return [
    '// AUTO-GENERATED by scripts/privacy/generate-breach-recipient-surfaces.mjs.',
    '// Do not edit by hand. The derivation guard fails closed if this file drifts.',
    '',
    'export const BREACH_RECIPIENT_SURFACES = ' + JSON.stringify(catalogue, null, 2) + ' as const;',
    '',
    "export type BreachRecipientSurfaceDescriptor = (typeof BREACH_RECIPIENT_SURFACES)[number];",
    "export type BreachAffectedSurface = BreachRecipientSurfaceDescriptor['surface'];",
    "export type BreachRecipientAuthority = BreachRecipientSurfaceDescriptor['authority'];",
    '',
  ].join('\n');
}

function main() {
  const rendered = renderGeneratedSource(deriveBreachRecipientSurfaces());
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(GENERATED_PATH) ? fs.readFileSync(GENERATED_PATH, 'utf8') : '';
    if (current !== rendered) {
      console.error('Breach recipient surface catalogue is stale. Regenerate before merging.');
      process.exitCode = 1;
    }
    return;
  }

  fs.mkdirSync(path.dirname(GENERATED_PATH), { recursive: true });
  fs.writeFileSync(GENERATED_PATH, rendered);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
