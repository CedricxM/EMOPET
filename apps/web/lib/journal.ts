/** Clé mois "YYYY-MM" à partir d'une date ISO. */
export function monthKey(iso: string): string {
  return iso.slice(0, 7);
}

/** Mois disponibles (clés "YYYY-MM"), triés du plus récent au plus ancien. */
export function availableMonths(entries: JournalEntry[]): string[] {
  return Array.from(new Set(entries.map((e) => monthKey(e.occurredAt)))).sort((a, b) => b.localeCompare(a));
}

export interface MonthSummary {
  totalEntries: number;
  walksCount: number;
  photosCount: number;
  milestonesCount: number;
}

export function monthSummary(entries: JournalEntry[]): MonthSummary {
  return {
    totalEntries: entries.length,
    walksCount: entries.filter((e) => e.type === 'walk_recorded').length,
    photosCount: entries.reduce(
      (n, e) => n + ((e.type === 'photo_text' || e.type === 'walk_recorded') ? e.photoUrls.length : 0),
      0,
    ),
    milestonesCount: entries.filter((e) => e.type === 'milestone').length,
  };
}

/** Regroupe les entrées par jour (clé "YYYY-MM-DD"), triées DESC. */
export function groupByDay(entries: JournalEntry[]): Array<[string, JournalEntry[]]> {
  const sorted = [...entries].sort((a, b) => b.occurredAt.localeCompare(a.occurredAt));
  const map = new Map<string, JournalEntry[]>();
  for (const e of sorted) {
    const day = e.occurredAt.slice(0, 10);
    const list = map.get(day);
    if (list) list.push(e);
    else map.set(day, [e]);
  }
  return Array.from(map.entries());
}

const DAYS = ['Dimanche', 'Lundi', 'Mardi', 'Mercredi', 'Jeudi', 'Vendredi', 'Samedi'];
const MONTHS = [
  'janvier', 'février', 'mars', 'avril', 'mai', 'juin',
  'juillet', 'août', 'septembre', 'octobre', 'novembre', 'décembre',
];

/** "Jeudi 29 mai" à partir d'une clé jour "YYYY-MM-DD". */
export function formatDayHeader(dayKey: string): string {
  const d = new Date(`${dayKey}T12:00:00`);
  return `${DAYS[d.getDay()]} ${d.getDate()} ${MONTHS[d.getMonth()]}`;
}

/** "Mai 2026" à partir d'une clé mois "YYYY-MM". */
export function formatMonthLabel(key: string): string {
  const [y, m] = key.split('-');
  const label = MONTHS[Number(m) - 1] ?? '';
  return `${label.charAt(0).toUpperCase()}${label.slice(1)} ${y}`;
}

export function formatTime(iso: string): string {
  return new Date(iso).toLocaleTimeString('fr-FR', { hour: '2-digit', minute: '2-digit' });
}

export function formatDuration(seconds: number): string {
  const h = Math.floor(seconds / 3600);
  const m = Math.round((seconds % 3600) / 60);
  return h > 0 ? `${h} h ${m.toString().padStart(2, '0')}` : `${m} min`;
}

export function formatDistance(meters: number): string {
  return meters >= 1000 ? `${(meters / 1000).toFixed(1)} km` : `${meters} m`;
}

export function formatDateLong(iso: string): string {
  const d = new Date(iso);
  return `${d.getDate()} ${MONTHS[d.getMonth()]} ${d.getFullYear()}`;
}

const ENTRY_TYPES = new Set<EntryType>(['photo_text', 'walk_recorded', 'milestone', 'observation', 'vet_visit']);
const MAX_JOURNAL_CONTENT_LENGTH = 2000;
const MAX_JOURNAL_TITLE_LENGTH = 160;
const MAX_JOURNAL_PHOTOS = 4;
const MAX_JOURNAL_PHOTO_URL_LENGTH = 4096;

/** Validation serveur minimale d'une entrée du carnet (entrée construite côté client). */
export function validateJournalEntry(e: Partial<JournalEntry>): string[] {
  const errors: string[] = [];
  if (!e.id) errors.push('id manquant.');
  if (!e.type || !ENTRY_TYPES.has(e.type)) errors.push("Type d'entrée invalide.");
  if (!e.occurredAt || Number.isNaN(new Date(e.occurredAt).getTime())) errors.push('Date invalide.');
  if (e.title && e.title.length > MAX_JOURNAL_TITLE_LENGTH) errors.push('Titre trop long.');
  if ('content' in e && typeof (e as { content?: unknown }).content === 'string') {
    const content = (e as { content?: string }).content ?? '';
    if (content.length > MAX_JOURNAL_CONTENT_LENGTH) errors.push('Contenu trop long.');
  }
  if ('photoUrls' in e && Array.isArray((e as { photoUrls?: unknown }).photoUrls)) {
    const photoUrls = (e as { photoUrls?: string[] }).photoUrls ?? [];
    if (photoUrls.length > MAX_JOURNAL_PHOTOS) errors.push('Trop de photos.');
    if (photoUrls.some((url) => typeof url !== 'string' || url.length > MAX_JOURNAL_PHOTO_URL_LENGTH)) {
      errors.push('Photo invalide.');
    }
  }
  if ((e.type === 'observation' || e.type === 'photo_text') && !('content' in e && (e as { content?: string }).content?.trim())) {
    errors.push('Contenu requis pour ce type.');
  }
  return errors;
}
