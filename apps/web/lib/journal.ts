export type EntryType = 'photo_text' | 'walk_recorded' | 'milestone' | 'observation' | 'vet_visit';

interface BaseEntry {
  id: string;
  /** ISO 8601. */
  occurredAt: string;
  title?: string;
  /** Vrai pour les jalons générés par le système (non éditables). */
  isAutoGenerated?: boolean;
}

export interface PhotoTextEntry extends BaseEntry {
  type: 'photo_text';
  content: string;
  /** Data URLs (prototype) ou URLs distantes. */
  photoUrls: string[];
  activityTag?: ActivityTag;
  locationName?: string;
}

export interface WalkEntry extends BaseEntry {
  type: 'walk_recorded';
  content?: string;
  durationSeconds: number;
  distanceMeters: number;
  elevationGainMeters?: number;
  weather?: { tempC: number; conditions: string };
  photoUrls: string[];
  locationName?: string;
}

export interface MilestoneEntry extends BaseEntry {
  type: 'milestone';
  content: string;
  milestoneKind: string;
}

export interface ObservationEntry extends BaseEntry {
  type: 'observation';
  /** Max 280 caractères (format court). */
  content: string;
}

export interface VetVisitEntry extends BaseEntry {
  type: 'vet_visit';
  visitType: 'annual' | 'vaccine' | 'control' | 'other';
  vetName?: string;
  content?: string;
  /** ISO date d'un rappel optionnel. */
  nextVisitReminder?: string;
}

export type JournalEntry =
  | PhotoTextEntry
  | WalkEntry
  | MilestoneEntry
  | ObservationEntry
  | VetVisitEntry;

