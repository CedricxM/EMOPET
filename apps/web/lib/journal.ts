export const JOURNAL_OWNER_HEADER = 'x-journal-owner-token';
const JOURNAL_OWNER_TOKEN_KEY = 'breiz-journal-owner-token';

function makeOwnerToken(): string {
  const uuid = globalThis.crypto?.randomUUID?.();
  return uuid ? `journal-${uuid}` : `journal-${Date.now()}-${Math.random().toString(36).slice(2, 10)}`;
}

export function getJournalOwnerToken(): string {
  if (typeof window === 'undefined') return '';
  try {
    const existing = localStorage.getItem(JOURNAL_OWNER_TOKEN_KEY);
    if (existing) return existing;
    const created = makeOwnerToken();
    localStorage.setItem(JOURNAL_OWNER_TOKEN_KEY, created);
    return created;
  } catch {
    return makeOwnerToken();
  }
}

